"""Regenerate the native species browser from the authoritative curation index."""
import json
import unicodedata
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
entries = json.loads((ROOT / 'data/heritage-index.json').read_text())['entries']
assert [e['national_dex'] for e in entries] == list(range(1,808))
text = '/* Generated by scripts/build_frontend_catalog.py. */\n'
text += 'const char* const lbx_species[LBX_DEX_COUNT] = {\n'
text += ',\n'.join(json.dumps(unicodedata.normalize('NFKD',e['species'].replace('♀','-F').replace('♂','-M')).encode('ascii','ignore').decode()) for e in entries) + '\n};\n'
text += 'const unsigned char lbx_generations[LBX_DEX_COUNT] = {\n'
text += ','.join(str(e['debut_generation']) for e in entries) + '\n};\n'
(ROOT / '3ds/LegacyBox3DS/source/catalog.inc').write_text(text)
